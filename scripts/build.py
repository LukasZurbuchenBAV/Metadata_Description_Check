#!/usr/bin/env python3
"""Build the checked-in, standalone HTML. Python stdlib only; no npm dependencies."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
IMPORT = re.compile(r"^import\s+[^;\n]+\s+from\s+(['\"])(\.[^'\"]+)\1;[ \t]*$", re.MULTILINE)
EXPORT = re.compile(r"^export (?=(?:async )?(?:const|let|function|class)\b)", re.MULTILINE)


def bundle(entry, standalone=False):
    parts, visited = [], set()

    def visit(path):
        path = path.resolve()
        if path in visited:
            return
        if not path.is_relative_to(ROOT / 'src'):
            raise ValueError(f'Unexpected dependency: {path}')
        visited.add(path)
        source = path.read_text()
        for dependency in IMPORT.finditer(source):
            visit(path.parent / dependency[2])
        source = EXPORT.sub('', IMPORT.sub('', source))
        if standalone and path.name == 'worker-loader.js':
            target = "return new Worker(new URL('./inference-worker.js', import.meta.url), {type:'module'});"
            if source.count(target) != 1:
                raise ValueError('Worker loader changed; update the standalone replacement')
            source = source.replace(target, 'return createBlobWorker(STANDALONE_WORKER_SOURCE);')
        if re.search(r'^\s*(?:import|export)\s', source, re.MULTILINE) or 'import.meta' in source:
            raise ValueError(f'Unsupported module syntax in {path.name}')
        parts.append(f'// {path.relative_to(ROOT)}\n{source.strip()}')

    visit(entry)
    return '\n\n'.join(parts)


def build():
    worker = bundle(ROOT / 'src/inference-worker.js')
    app = bundle(ROOT / 'src/app.js', standalone=True)
    javascript = "'use strict';\n(()=>{\nconst STANDALONE_WORKER_SOURCE = " + json.dumps(worker, ensure_ascii=False) + ';\n' + app + '\n})();'
    # Prevent the HTML parser from treating a JavaScript string as a script end tag.
    javascript = re.sub(r'</script', r'<\\/script', javascript, flags=re.IGNORECASE)
    template = (ROOT / 'src/index.template.html').read_text()
    for marker in ['<!-- APP_STYLES -->', '<!-- APP_SCRIPT -->']:
        if template.count(marker) != 1:
            raise ValueError(f'Missing or duplicated template marker: {marker}')
    template = template.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by scripts/build.py. Edit src/ and styles.css; no build is needed to use this file. -->', 1)
    return template.replace('<!-- APP_STYLES -->', '<style>\n' + (ROOT / 'styles.css').read_text().rstrip() + '\n</style>').replace('<!-- APP_SCRIPT -->', '<script>\n' + javascript + '\n</script>')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if index.html is not up to date')
    args = parser.parse_args()
    output = build()
    target = ROOT / 'index.html'
    if args.check:
        if target.read_text() != output:
            parser.exit(1, 'index.html is outdated; run python3 scripts/build.py\n')
    else:
        target.write_text(output)
